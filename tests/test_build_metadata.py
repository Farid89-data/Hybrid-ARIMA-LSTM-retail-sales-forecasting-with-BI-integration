"""D10 document metadata and PEND-FIG missing-figure placeholder."""
import shutil
import sys
from pathlib import Path

import docx
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "docbuild"))
import build_docx as bd  # noqa: E402

BANNED = ("claude", "anthropic", "jshort", "frd ngb", "gpt", "copilot")


def test_apply_core_properties(tmp_path):
    if not bd.TEMPLATE.exists():
        pytest.skip("template docx missing")
    copy = tmp_path / "t.docx"
    shutil.copy(bd.TEMPLATE, copy)
    ident = bd.load_identity()
    bd.apply_core_properties(copy, ident)
    cp = docx.Document(str(copy)).core_properties
    assert cp.author == ident["student_name"] == "Farid Negahbani"
    assert cp.last_modified_by == ident["student_name"]
    assert cp.title == ident["title"]
    for attr in ("author", "last_modified_by", "title", "subject", "keywords", "comments",
                 "category", "content_status", "identifier", "version"):
        value = (getattr(cp, attr) or "").lower()
        assert not any(w in value for w in BANNED), (attr, value)


def test_missing_figure_becomes_pending_placeholder():
    if not bd.TEMPLATE.exists():
        pytest.skip("template docx missing")
    md = ("# Test chapter\n\n::: figure id=fig:nope file=outputs/figures/does_not_exist_xyz.png width=10\n"
          "caption: A figure that is not generated yet\n"
          "alt: none\n:::\n")
    b = bd.Builder(bd.TEMPLATE, bd.REFS_JSON)
    blocks = bd.parse_markdown(md)
    b.assign_numbers([("03_test", blocks)])
    b.render(blocks, part="03_test")
    text = "\n".join(p.text for p in b.doc.paragraphs)
    assert "PENDING: figure does_not_exist_xyz.png is generated by" in text
    assert "A figure that is not generated yet" in text
    assert any("does_not_exist_xyz.png" in w for w in b.warnings)
